# for loop: iterating over a list, a tuple and a string

print("List Iteration")

items = ["geeks", "for", "geeks"]

for item in items:
    print(item)


# for loop, iterating over a Tuple

print("\nTuple Iteration")

tup = ("geeks", "for", "geeks")

for item in tup:
    print(item)


# for loop, iterating over a String (one character at a time)

print("\nString Iteration")

text = "Geeks"

for char in text:
    print(char)
